# This program checks whether a customer qualifies for a free mobile phone.

name = input("What is your name: ")
bill_amount = int(input("Enter your bill amount: "))

if bill_amount >= 1000:
    print("Congratulations " + name + ", you get a mobile phone for free! Your bill amount is " + str(bill_amount) + ".")
else:
    print("Thanks for shopping, " + name + ".")


